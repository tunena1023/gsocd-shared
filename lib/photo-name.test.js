/* node lib/photo-name.test.js -- el nombre de las fotos de servicio (18/10/2026). */
'use strict';
const assert = require('assert');
const pl = require('./photo-log');
const p = n => pl.parseServicePhoto(n);
let r = p('svc-Hallway_vacuuming-2026-10-17_153045-a1b2c3-gal.jpg');
assert.ok(r && r.service === 'Hallway vacuuming' && r.rand === 'a1b2c3' && r.gallery && r.h === '15', 'random + gal');
r = p('svc-Hallway_vacuuming-2026-10-17_153045-a1b2c3.jpg');
assert.ok(r && r.service === 'Hallway vacuuming' && r.rand === 'a1b2c3' && !r.gallery, 'random only');
r = p('svc-Hallway_vacuuming-2026-10-17_153045.jpg');
assert.ok(r && r.rand === '' && !r.gallery, 'old name, no suffix');
r = p('svc-Hallway_vacuuming-2026-10-17_153045-gal.jpg');
assert.ok(r && r.rand === '' && r.gallery, 'gal without random is gallery, not a random "gal"');
r = p('svc-Kitchen_-_Deep-2026-10-17_153045-x9-gal.jpeg');
assert.ok(r && r.serviceSafe === 'Kitchen_-_Deep' && r.gallery, 'service with dashes');
assert.strictEqual(p('insp-2026-10-17_153045-a1.jpg'), null, 'not a service photo');
assert.strictEqual(pl.photoStamp('svc-X-2026-10-17_153045-a1b2-gal.jpg'), '2026-10-17_153045-a1b2');
assert.strictEqual(pl.photoStamp('insp-2026-10-17_153045-a1b2.jpg'), '2026-10-17_153045-a1b2');
assert.strictEqual(pl.photoStamp('svc-X-2026-10-17_153045-gal.jpg'), '2026-10-17_153045');
assert.strictEqual(pl.photoStamp('random.jpg'), '');
console.log('photo-name ok');
