'use strict';
const { dedupe } = require('./history-dedupe');
let ok = 0, fail = 0;
const check = (n, c, x) => { if (c) { ok++; console.log('OK  ', n); } else { fail++; console.log('FAIL', n, x === undefined ? '' : JSON.stringify(x)); } };
const row = (id, t, extra) => ({ id, fields: Object.assign({ OrderID: 'GS-1-1', ChangeType: 'Service Completed', ChangedBy: 'Ana', NewValue: 'Kitchen', ChangeDate: t }, extra || {}) });
let r = dedupe([row('1', '2026-10-21T13:45:53Z'), row('2', '2026-10-21T13:46:31Z'), row('3', '2026-10-21T13:47:10Z')]);
check('same click repeated within 60 s from the first: shown once', r.map(x => x.id).join() === '1,3', r.map(x => x.id));
r = dedupe([row('1', '2026-10-21T13:45:00Z'), row('2', '2026-10-21T13:45:10Z', { NewValue: 'Bath' })]);
check('different content: both stay', r.length === 2);
r = dedupe([row('1', '2026-10-21T13:45:00Z'), row('2', '2026-10-21T13:45:10Z', { ChangedBy: 'Luis' })]);
check('different person: both stay', r.length === 2);
r = dedupe([row('1', '2026-10-21T13:45:00Z', { ChangeType: 'Service Scheduled' }), row('2', '2026-10-21T13:45:01Z', { ChangeType: 'Service Scheduled' })]);
check('"Service Scheduled" is never merged', r.length === 2);
r = dedupe([row('1', '2026-10-21T13:45:00Z', { NewValue: '{"a":1,"at":"x"}' }), row('2', '2026-10-21T13:45:20Z', { NewValue: '{"at":"y","a":1}' })]);
check('JSON with only the time different: one', r.length === 1);
const flat = [{ OrderID: 'A', ChangeType: 'X', ChangeDate: '2026-10-21T10:00:00Z' }, { OrderID: 'A', ChangeType: 'X', ChangeDate: '2026-10-21T10:00:30Z' }];
check('flat rows work too and come back as the same objects', dedupe(flat).length === 1 && dedupe(flat)[0] === flat[0]);
const one = [row('1', 'x')];
check('one row / no date: untouched', dedupe(one) === one && dedupe([row('1', 'bad'), row('2', 'bad')]).length === 2);
console.log('\n' + ok + ' OK, ' + fail + ' FAIL');
process.exit(fail ? 1 : 0);
